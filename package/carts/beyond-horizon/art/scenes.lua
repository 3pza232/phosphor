-- art/scenes.lua —— 八个场景图（每个 80x25，贴内容区 y=2 起的对话美术槽）。
--
-- 约定：
--   * 行是纯 ASCII；'.' 是 sprite 的透明字符（本文件不用它当墨）；
--   * 每块带 colors（字符 → 语义键）与 note（构图要点）；anchor 一律 top-left；
--   * 铭文（CRYO-03 / OBS-2 / 40 rs…）是仪器装饰，不参与本地化；
--     程序若用本地化标题，画在场景之上即可（铭文都很靠近边缘）。
local U = require("art.util")

local function merge(...)
  local out = {}
  for _, src in ipairs({ ... }) do
    if src then for k, v in pairs(src) do out[k] = v end end
  end
  return out
end

-- 八张场景图统一裁成 GDD 的槽位：80 列 × 25 行（对话界面 y=2..26 的整块）。
-- drop 是行号（0 基），只删装饰/空行，不重排其余行——构图与道具位置保持不变。
local function scene(id, art, colors, note, drop)
  local b = U.block{ id = id, art = art, colors = merge(U.ascii_ink(), colors),
                     anchor = "top-left", note = note }
  return U.fit(b, 80, 25, drop)
end

