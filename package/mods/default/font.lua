-- 覆盖层 Mod：把字号可调上限从 24 抬高到 28（多一档更大的字）
--
-- 覆盖的是字体方案 theme/font/default/font.lua —— Mod 里只放"想改的那份内容"，
-- 其余与出厂一致。引擎把方案声明的 min/max 当作设置界面"字号"行的可调范围，
-- 于是用户能把字号调到 28（出厂只到 24）。硬上限是 32（再大字形放大就发糊了）。
return {
  size = 16,                    -- 默认字号不变
  min = 12,
  max = 28,                     -- ← 抬高上限（出厂 24）
  order = { "font", "font-cn" },
}
